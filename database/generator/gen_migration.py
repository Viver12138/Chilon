"""Create an Alembic revision from the generated DDL.

Migrations are immutable snapshots: the SQL is embedded in the revision file, so
later registry changes cannot silently rewrite history. `database/tests/check_migration_sync.py`
compares the latest revision's recorded schema hash with the current generated
DDL and fails when a new revision is required.

Usage:
    python database/generator/gen_migration.py --id 0001_k009_baseline --slug "k009 baseline"
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DDL = ROOT / "database" / "generated" / "k009.sql"
MANIFEST = ROOT / "database" / "generated" / "manifest.json"
VERSIONS = ROOT / "backend" / "migrations" / "versions"

TEMPLATE = '''"""{slug}

Revision ID: {revision}
Revises: {down_revision}
Create Date: generated by database/generator/gen_migration.py

Registry snapshot (do not edit by hand):
    registry_hash: {registry_hash}
    schema_hash:   {schema_hash}
    tables:        {tables}
"""

from __future__ import annotations

from alembic import op

revision = "{revision}"
down_revision = {down_revision!r}
branch_labels = None
depends_on = None

REGISTRY_HASH = "{registry_hash}"
SCHEMA_HASH = "{schema_hash}"

TABLES = {tables_list}

SQL = r"""--- generated DDL ---
{sql}
"""


def split_statements(sql: str) -> list[str]:
    """Split on ';' while respecting single quotes and $$ dollar-quoted bodies."""
    out: list[str] = []
    buf: list[str] = []
    i = 0
    n = len(sql)
    in_single = False
    in_dollar = False
    while i < n:
        ch = sql[i]
        if not in_single and sql.startswith("$$", i):
            in_dollar = not in_dollar
            buf.append("$$")
            i += 2
            continue
        if not in_dollar and ch == "'":
            in_single = not in_single
            buf.append(ch)
            i += 1
            continue
        if ch == ";" and not in_single and not in_dollar:
            stmt = "".join(buf).strip()
            if stmt and not _is_comment_only(stmt):
                out.append(stmt)
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1
    tail = "".join(buf).strip()
    if tail and not _is_comment_only(tail):
        out.append(tail)
    return out


def _is_comment_only(stmt: str) -> bool:
    for line in stmt.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("--"):
            return False
    return True


def upgrade() -> None:
    for statement in split_statements(SQL):
        op.execute(statement)


def downgrade() -> None:
    for table in reversed(TABLES):
        op.execute(f"DROP TABLE IF EXISTS {{table}} CASCADE")
    for fn in (
        "app_current_execution_id",
        "app_current_request_id",
        "app_current_user_id",
    ):
        op.execute(f"DROP FUNCTION IF EXISTS public.{{fn}}()")
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--id", required=True)
    parser.add_argument("--slug", default="migration")
    parser.add_argument("--down", default=None, help="previous revision id")
    args = parser.parse_args()

    if not DDL.exists() or not MANIFEST.exists():
        print("run database/generator/generate_ddl.py first")
        return 1

    sql = DDL.read_text(encoding="utf-8")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    tables = manifest["included_tables"]

    VERSIONS.mkdir(parents=True, exist_ok=True)
    target = VERSIONS / f"{args.id}.py"
    if target.exists():
        print(f"refusing to overwrite existing revision {target.name}")
        return 1

    content = TEMPLATE.format(
        slug=args.slug,
        revision=args.id,
        down_revision=args.down,
        registry_hash=manifest["registry_hash"],
        schema_hash=manifest["schema_hash"],
        tables=len(tables),
        tables_list=json.dumps(tables, indent=4),
        sql=sql.rstrip(),
    )
    target.write_text(content, encoding="utf-8")
    compile(content, str(target), "exec")
    print(f"wrote {target.relative_to(ROOT)}")
    print(f"schema_hash {manifest['schema_hash'][:12]}  tables {len(tables)}")

    # the embedded SQL must round-trip exactly
    embedded = sql.rstrip()
    if hashlib.sha256((embedded + "\n").encode("utf-8")).hexdigest() != manifest["schema_hash"]:
        print("WARN: embedded SQL hash differs from manifest schema_hash")
        return 1
    print("embedded SQL matches the generated DDL")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
